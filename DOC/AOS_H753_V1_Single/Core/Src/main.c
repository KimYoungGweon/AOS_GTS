void UART2_Recover(void)
{
    // 1) UART disable
    CLEAR_BIT(huart2.Instance->CR1, USART_CR1_UE);
    __DSB();

    // 2) UART clock OFF (Hard reset)
    __HAL_RCC_USART2_CLK_DISABLE();
    HAL_Delay(2);

    // 3) Clear error flags (safety)
    __HAL_UART_CLEAR_OREFLAG(&huart2);
    __HAL_UART_CLEAR_FEFLAG(&huart2);
    __HAL_UART_CLEAR_NEFLAG(&huart2);
    __HAL_UART_CLEAR_PEFLAG(&huart2);
    __HAL_UART_CLEAR_IDLEFLAG(&huart2);

    // 4) UART clock ON
    __HAL_RCC_USART2_CLK_ENABLE();

    // 5) HAL 재초기화
    HAL_UART_DeInit(&huart2);
    HAL_UART_Init(&huart2);

    // 6) RX FIFO flush (H7에서 매우 중요)
    huart2.Instance->RQR |= USART_RQR_RXFRQ;

    // 7) RX Interrupt 재시작
    HAL_UART_Receive_IT(&huart2, &rx1_byte, 1);
}



