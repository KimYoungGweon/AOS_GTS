void Wave_Frq_and_Duty_Update(float frq, float duty)
{
	MData.OSET.Frq = frq;
	MData.OSET.Duty = duty;

	if (frq <= 0.0f || duty < 0.0f || duty > 100.0f) return;

	uint32_t period = (uint32_t)(480000000UL / (uint32_t)(frq * 1000UL));
	uint32_t compare = (uint32_t)((period * (100.0f - duty)) / 100.0f);

	HRTIM_SetPeriod(&hhrtim, HRTIM_TIMERINDEX_TIMER_A, period);
	HRTIM_SetCompare(&hhrtim, HRTIM_TIMERINDEX_TIMER_A, HRTIM_COMPAREUNIT_1, compare);

	HAL_HRTIM_WaveformCounterStart(&hhrtim, HRTIM_TIMERID_MASTER);
	MData.START_CTL.IsStartFlag=true;
}

void HRTIM_SetPeriod(HRTIM_HandleTypeDef *hhrtim, uint32_t TimerIdx, uint32_t Period)
{
    hhrtim->Instance->sTimerxRegs[TimerIdx].PERxR = Period;
}

void HRTIM_SetCompare(HRTIM_HandleTypeDef *hhrtim, uint32_t TimerIdx, uint32_t CompareUnit, uint32_t Compare)
{
    switch (CompareUnit)
    {
        case HRTIM_COMPAREUNIT_1:
            hhrtim->Instance->sTimerxRegs[TimerIdx].CMP1xR = Compare;
            break;
        case HRTIM_COMPAREUNIT_2:
            hhrtim->Instance->sTimerxRegs[TimerIdx].CMP2xR = Compare;
            break;
        case HRTIM_COMPAREUNIT_3:
            hhrtim->Instance->sTimerxRegs[TimerIdx].CMP3xR = Compare;
            break;
        case HRTIM_COMPAREUNIT_4:
            hhrtim->Instance->sTimerxRegs[TimerIdx].CMP4xR = Compare;
            break;
    }
}
